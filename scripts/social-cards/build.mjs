// Builds every generated brand asset: SVG source in the repo, PNG for posting.
//
//   npm run social-cards
//
//   assets/social/grainlify-launch-*        1200x675 / 1200x627   share cards
//   assets/social/grainlify-early-access-*  1200x675 / 1200x627   campaign cards
//   assets/social/grainlify-banner-*        1500x500 / 1128x191   profile banners
//   assets/social/grainlify-avatar-*        400x400               profile pictures
//
// Five properties this script exists to hold, none of which survive a
// hand-exported image:
//
//   1. Every colour is read from src/styles/brand.css at build time. No hex is
//      typed in this directory. Change the palette there and re-run; the assets
//      follow. If a role's token disappears, the build fails rather than
//      quietly falling back to a default.
//   2. Every text/background pair is measured for WCAG AA contrast and the
//      build FAILS on a failure. White-on-gold measured 2.61 in the light-mode
//      audit - a pair that looked fine and was not - so "check the contrast"
//      is a gate here, not a note in a comment.
//   3. Every drawn element is measured after rendering, in the real font, and
//      the build fails if it crosses a safe edge. A standalone SVG does not
//      wrap or shrink text: an over-long line runs off the asset silently.
//   4. Banners additionally clear the profile-picture overlay, and avatars
//      clear the circular crop. Both are places where an asset is not merely
//      tight but actively covered, and neither is visible in the flat file.
//   5. The campaign card is verified at feed-thumbnail width by counting the
//      display number's actual painted pixels, because that is the size most
//      impressions of it are seen at and a card that only works at 1200px
//      does not work.
//
// The copy lives in content.mjs. This file holds no words of its own.

