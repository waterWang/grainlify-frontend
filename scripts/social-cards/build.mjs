/** The lockup: real mark path, scaled from the asset's own viewBox, plus the
 *  wordmark optically centred on the mark rather than sharing its baseline. */
function lockup({ x, y, logoSize, wordmarkSize, markFill, wordFill, gap = 14 }) {
  const scale = logoSize / logo.vbH
  const logoW = (logoSize * logo.vbW) / logo.vbH
  return `    <g transform="translate(${x}, ${y}) scale(${scale.toFixed(5)})">
      <path d="${logo.path}" fill="${markFill}"/>
    </g>
    <text class="wordmark" x="${x + logoW + gap}" y="${y + logoSize / 2}" dominant-baseline="central" fill="${wordFill}">${esc(BANNER_CONTENT.wordmark)}</text>`
}

