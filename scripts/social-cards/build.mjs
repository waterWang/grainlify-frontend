/**
 * The lightest ground any text on this banner can land on: the base colour
 * with every texture layer flattened onto it. Contrast is audited against this
 * rather than against the flat ground, because a dot under a letter is part of
 * that letter's background whether or not it was drawn as decoration.
 */
function worstBg(b) {
  const layers = []
  if (b.texture?.ghost) layers.push({ colour: C.gold, alpha: b.texture.ghost.opacity })
  if (b.texture) layers.push({ colour: C.gold, alpha: b.texture.opacity })
  return compositeOver(C.ground, layers)
}

function textureMarkup(b) {
  if (!b.texture) return ''
  const { spacing, radius, opacity, ghost } = b.texture
  const half = spacing / 2

  // A half-drop tile: two dots per cell puts the lattice on the diagonal
  // without drawing any lines, which is the "sparse" reading rather than the
  // "graph paper" one.
  const pattern = `    <pattern id="dots" width="${spacing}" height="${spacing}" patternUnits="userSpaceOnUse">
      <circle cx="${half / 2}" cy="${half / 2}" r="${radius}" fill="${C.gold}" fill-opacity="${opacity}"/>
      <circle cx="${half + half / 2}" cy="${half + half / 2}" r="${radius}" fill="${C.gold}" fill-opacity="${opacity}"/>
    </pattern>`

  let ghostMarkup = ''
  if (ghost) {
    const scale = ghost.height / logo.vbH
    const y = ghost.centreY - ghost.height / 2
    ghostMarkup = `
  <g transform="translate(${ghost.x}, ${y}) scale(${scale.toFixed(5)})" opacity="${ghost.opacity}">
    <!-- Valueless attributes are legal HTML but not legal XML, and an SVG is
         parsed as XML: writing this bare made the whole document fail to parse
         and render blank. -->
    <path data-decorative="true" d="${logo.path}" fill="${C.gold}"/>
  </g>`
  }

  return `  <defs>
${pattern}
  </defs>

  <rect data-decorative="true" width="${b.width}" height="${b.height}" fill="url(#dots)"/>${ghostMarkup}`
}

/**
 * The vertical rule beside the type. Deliberately NOT decorative: it is a
 * drawn element with a position, so it has to clear the avatar overlay and the
 * crop windows like everything else. Marking it decorative to skip the check
 * would be marking it as "allowed to be covered", which it is not.
 */
function accentMarkup(b) {
  if (!b.accent) return ''
  const { x, width, top, bottom } = b.accent
  return `
    <rect x="${x}" y="${top}" width="${width}" height="${bottom - top}" rx="${width / 2}" fill="${C.gold}"/>`
}

function buildBannerSvg(b) {
  const { width, height } = b
  const label = `Grainlify. ${BANNER_CONTENT.lead} ${BANNER_CONTENT.hero}`

  const lockupMarkup = b.showLockup
    ? `\n${lockup({
        x: b.contentX,
        y: b.markTop,
        logoSize: b.logoSize,
        wordmarkSize: b.wordmarkSize,
        markFill: C.gold,
        wordFill: C.cream,
        gap: Math.round(b.logoSize * 0.4),
      })}\n`
    : ''

  const wordmarkRule = b.showLockup
    ? `\n    .wordmark { font-size: ${b.wordmarkSize}px; font-weight: 600; letter-spacing: -0.01em; }`
    : ''

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-label="${esc(label)}">
  <title>Grainlify — ${b.platform} banner</title>
${GENERATED_BY}
  <style>
    ${FONT_IMPORT}
    text { font-family: ${FONT_STACK}; }${wordmarkRule}
    .lead { font-size: ${b.lead.size}px; font-weight: 400; letter-spacing: 0; }
    .hero { font-size: ${b.hero.size}px; font-weight: 700; letter-spacing: -0.02em; }
  </style>

  <rect data-decorative="true" width="${width}" height="${height}" fill="${C.ground}"/>
${textureMarkup(b)}

  <g>${accentMarkup(b)}${lockupMarkup}
    <text class="lead" x="${b.contentX}" y="${b.lead.baseline}" fill="${C[b.lead.role]}">${esc(BANNER_CONTENT.lead)}</text>
    <text class="hero" x="${b.contentX}" y="${b.hero.baseline}" fill="${C[b.hero.role]}">${esc(BANNER_CONTENT.hero)}</text>
  </g>
</svg>
`
}

function bannerContrastPairs() {
  return BANNERS.flatMap((b) => {
    const bg = worstBg(b)
    const pairs = [
      { what: `${b.name} banner: lead line`, fg: C[b.lead.role], bg, px: b.lead.size, bold: false },
      { what: `${b.name} banner: hero line`, fg: C[b.hero.role], bg, px: b.hero.size, bold: true },
    ]
    if (b.accent) {
      pairs.push({ what: `${b.name} banner: accent rule`, fg: C.gold, bg, px: b.accent.width, graphic: true })
    }
    if (b.showLockup) {
      pairs.push(
        { what: `${b.name} banner: wordmark`, fg: C.cream, bg, px: b.wordmarkSize, bold: true },
        { what: `${b.name} banner: logo mark`, fg: C.gold, bg, px: b.logoSize, graphic: true },
      )
    }
    return pairs
  })
}

/**
 * The check the brief turns on: nothing may sit under the profile picture.
 *
 * The zone is anchored bottom-left because that is where both platforms put
 * the overlay. An element counts as violating if its box intersects the zone
 * at all - "mostly clear" is still partly covered.
 */
function bannerProblems(b, boxes) {
  const problems = []
  const zoneRight = b.avatarZone.width
  const zoneTop = b.height - b.avatarZone.height
  const safeRight = b.width - b.marginRight
  const safeBottom = b.height - b.marginTop

  for (const el of boxes) {
    const label = `${b.name} banner: ${el.kind === 'path' ? 'logo mark' : `"${el.label}"`}`
    if (el.left < zoneRight && el.bottom > zoneTop) {
      problems.push(
        `${label} intersects the profile-picture overlay ` +
          `(left ${el.left} < ${zoneRight}, bottom ${el.bottom} > ${zoneTop})`,
      )
    }
    if (el.right > safeRight) problems.push(`${label} ends at ${el.right}px, past the ${safeRight}px safe edge`)
    if (el.top < b.marginTop) problems.push(`${label} starts at ${el.top}px, above the ${b.marginTop}px margin`)
    if (el.bottom > safeBottom) problems.push(`${label} reaches ${el.bottom}px, below the ${safeBottom}px safe edge`)

    // Every crop window, not just the full canvas. This is what catches a
    // layout that is correct on desktop and loses a word on mobile.
    for (const crop of b.crops ?? []) {
      if (el.left < crop.left || el.right > crop.right) {
        problems.push(
          `${label} spans ${el.left}-${el.right}px, outside the ${crop.name} crop ` +
            `(${crop.left}-${crop.right}px)`,
        )
      }
      if (el.top < crop.top || el.bottom > crop.bottom) {
        problems.push(
          `${label} spans ${el.top}-${el.bottom}px vertically, outside the ${crop.name} crop ` +
            `(${crop.top}-${crop.bottom}px)`,
        )
      }
    }
  }
  return problems
}

