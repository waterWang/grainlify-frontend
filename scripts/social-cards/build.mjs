/**
 * The mark's PAINTED bounds, in viewBox units.
 *
 * Centring on the viewBox instead would centre the padding: the source asset's
 * box is 28.77 x 26.33 while the glyph inside it is neither centred nor
 * flush, so a "centred" avatar built from the viewBox sits visibly off. Probed
 * at 10x so rounding to whole device pixels is negligible.
 */
async function measureInk(browser) {
  const S = 10
  const probe = path.join(outDir, '.ink-probe.svg')
  writeFileSync(
    probe,
    `<svg xmlns="http://www.w3.org/2000/svg" width="${logo.vbW * S}" height="${logo.vbH * S}" viewBox="0 0 ${logo.vbW} ${logo.vbH}"><path d="${logo.path}" fill="#000"/></svg>`,
  )
  const { boxes } = await renderOne(browser, {
    svgPath: probe,
    pngPath: null,
    width: Math.ceil(logo.vbW * S),
    height: Math.ceil(logo.vbH * S),
    scale: 1,
  })
  rmSync(probe, { force: true })

  const p = boxes.find((b) => b.kind === 'path')
  if (!p) throw new Error('avatar: could not measure the mark')
  return { x: p.left / S, y: p.top / S, w: (p.right - p.left) / S, h: (p.bottom - p.top) / S }
}

function buildAvatarSvg(variant, ink) {
  const { size, markHeight } = AVATARS
  const centre = size / 2
  const scale = markHeight / ink.h
  // Map the ink's centre onto the canvas centre: tx + scale*inkCentre = centre.
  const tx = centre - scale * (ink.x + ink.w / 2)
  const ty = centre - scale * (ink.y + ink.h / 2)

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}" role="img" aria-label="Grainlify">
  <title>Grainlify — profile picture (${variant.name})</title>
${GENERATED_BY}
  <rect data-decorative="true" width="${size}" height="${size}" fill="${C[variant.ground]}"/>
  <g transform="translate(${tx.toFixed(3)}, ${ty.toFixed(3)}) scale(${scale.toFixed(5)})">
    <path d="${logo.path}" fill="${C[variant.mark]}"/>
  </g>
</svg>
`
}

/**
 * X crops the avatar to a circle. The mark has to sit inside the inscribed
 * circle with clearance, so the test is radial - the furthest corner of the
 * mark's box from the centre, not its left/right edges. A square-margin check
 * passes marks that get clipped on the diagonal.
 */
function avatarProblems(variant, boxes) {
  const centre = AVATARS.size / 2
  const mark = boxes.find((b) => b.kind === 'path')
  if (!mark) return [`${variant.name}: the mark did not render`]

  const corners = [
    [mark.left, mark.top],
    [mark.right, mark.top],
    [mark.left, mark.bottom],
    [mark.right, mark.bottom],
  ]
  const furthest = Math.max(...corners.map(([x, y]) => Math.hypot(x - centre, y - centre)))
  if (furthest > AVATARS.safeRadius) {
    return [
      `${variant.name}: the mark reaches ${furthest.toFixed(1)}px from centre, ` +
        `past the ${AVATARS.safeRadius}px safe radius — the circular crop would clip it`,
    ]
  }

  const offX = (mark.left + mark.right) / 2 - centre
  const offY = (mark.top + mark.bottom) / 2 - centre
  if (Math.abs(offX) > 1 || Math.abs(offY) > 1) {
    return [`${variant.name}: the mark is off-centre by (${offX.toFixed(1)}, ${offY.toFixed(1)})px`]
  }
  return []
}

