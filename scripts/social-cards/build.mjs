function buildCardSvg(size) {
  const { width, height, margin } = size

  const headline = CONTENT.headline
    .map((line, i) => {
      const y = size.headline.firstBaseline + i * size.headline.lineHeight
      return `    <text class="headline" x="${margin}" y="${y}" fill="${C[line.role]}">${esc(line.text)}</text>`
    })
    .join('\n')

  const support = CONTENT.support
    .map((line, i) => {
      const y = size.support.firstBaseline + i * size.support.lineHeight
      return `    <text class="support" x="${margin}" y="${y}" fill="${C.support}">${esc(line)}</text>`
    })
    .join('\n')

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-label="${esc(CONTENT.headline.map((l) => l.text).join(' '))}">
  <title>Grainlify — ${size.platform} share card</title>
${GENERATED_BY}
  <style>
    ${FONT_IMPORT}
    text { font-family: ${FONT_STACK}; }
    .wordmark { font-size: ${size.wordmarkSize}px; font-weight: 600; letter-spacing: -0.01em; }
    .headline { font-size: ${size.headline.size}px; font-weight: 700; letter-spacing: -0.022em; }
    .support  { font-size: ${size.support.size}px; font-weight: 400; letter-spacing: 0; }
    .footer   { font-size: ${size.footer.size}px; font-weight: 600; letter-spacing: 0.01em; }
  </style>

  <rect data-decorative="true" width="${width}" height="${height}" fill="${C.ground}"/>

  <g>
${lockup({
    x: margin,
    y: margin,
    logoSize: size.logoSize,
    wordmarkSize: size.wordmarkSize,
    markFill: C.gold,
    wordFill: C.cream,
  })}

${headline}

${support}

    <text class="footer" x="${margin}" y="${size.footer.baseline}" fill="${C.gold}">${esc(CONTENT.footer)}</text>
  </g>
</svg>
`
}

function cardContrastPairs() {
  const pairs = []
  for (const size of SIZES) {
    pairs.push({ what: `${size.name}: wordmark`, fg: C.cream, bg: C.ground, px: size.wordmarkSize, bold: true })
    for (const line of CONTENT.headline) {
      pairs.push({
        what: `${size.name}: headline "${line.text.slice(0, 26)}"`,
        fg: C[line.role],
        bg: C.ground,
        px: size.headline.size,
        bold: true,
      })
    }
    pairs.push({ what: `${size.name}: supporting line`, fg: C.support, bg: C.ground, px: size.support.size, bold: false })
    pairs.push({ what: `${size.name}: footer`, fg: C.gold, bg: C.ground, px: size.footer.size, bold: false })
    pairs.push({ what: `${size.name}: logo mark`, fg: C.gold, bg: C.ground, px: size.logoSize, graphic: true })
  }
  return pairs
}

