/**
 * Legibility at the size the card is actually seen, measured from the pixels
 * of the thumbnail itself.
 *
 * A text element's bounding box is the font's em box - ascent plus descent,
 * about 1.21em - not the visible glyphs. For "300" at 240px that box is 291px
 * tall while the digits are nearer 174, so checking the box would overstate
 * the number by two thirds and could pass a card whose digits had actually
 * gone to mush. This reads the rendered PNG and finds the rows that actually
 * contain the display colour.
 *
 * The scan window is derived from measurements rather than guessed: it starts
 * below the logo mark, which is the same yellow and shares the number's
 * x-range, and it reports rather than silently trusts a window that clipped
 * the ink it was supposed to contain.
 */
async function measureDisplayInk(c, boxes, thumbPath) {
  const scale = c.thumbnail.width / c.width
  const display = boxes.find((b) => b.cls === 'display')
  const mark = boxes.find((b) => b.kind === 'path')
  if (!display) return { problems: [`${c.name} campaign: no display number to measure`] }

  const x0 = Math.round(display.left * scale)
  const x1 = Math.round(display.right * scale)
  // Exclude the lockup: it is the same colour and sits directly above.
  const yTop = Math.max(display.top, (mark?.bottom ?? 0) + 2)
  const y0 = Math.round(yTop * scale)
  const y1 = Math.round(display.bottom * scale)

  const { data, info } = await sharp(thumbPath).raw().toBuffer({ resolveWithObject: true })
  const target = [1, 3, 5].map((i) => parseInt(C.gold.slice(i, i + 2), 16))
  const near = (i) =>
    Math.abs(data[i] - target[0]) < 40 &&
    Math.abs(data[i + 1] - target[1]) < 40 &&
    Math.abs(data[i + 2] - target[2]) < 40

  let inkTop = null
  let inkBottom = null
  for (let y = y0; y < Math.min(y1, info.height); y++) {
    let hit = false
    for (let x = Math.max(0, x0); x < Math.min(x1, info.width); x++) {
      if (near((y * info.width + x) * info.channels)) {
        hit = true
        break
      }
    }
    if (hit) {
      if (inkTop === null) inkTop = y
      inkBottom = y
    }
  }

  const problems = []
  if (inkTop === null) {
    problems.push(`${c.name} campaign: found no display-coloured pixels in the thumbnail`)
    return { problems }
  }
  if (inkTop <= y0) {
    problems.push(
      `${c.name} campaign: the display ink reaches the top of the scan window (${y0}px), ` +
        `so the measurement may be clipped or catching the lockup`,
    )
  }

  const inkPx = inkBottom - inkTop + 1
  if (inkPx < c.thumbnail.minDisplayPx) {
    problems.push(
      `${c.name} campaign: "${display.label}" renders ${inkPx}px of actual ink at ` +
        `${c.thumbnail.width}px wide, under the ${c.thumbnail.minDisplayPx}px legibility floor`,
    )
  }
  return { problems, inkPx, boxPx: Math.round((display.bottom - display.top) * scale) }
}

/** The numeral's width is the font's business, not ours, so the gap beside it
 *  is measured rather than trusted. */
function campaignGapProblems(c, boxes) {
  const display = boxes.find((b) => b.cls === 'display')
  const suffix = boxes.filter((b) => b.cls === 'suffix')
  if (!display || !suffix.length) return [`${c.name} campaign: could not measure the display pairing`]

  const gap = Math.min(...suffix.map((s) => s.left)) - display.right
  if (gap < c.suffixGap.min || gap > c.suffixGap.max) {
    return [
      `${c.name} campaign: "founding spots" sits ${gap}px from "${display.label}", ` +
        `outside the ${c.suffixGap.min}-${c.suffixGap.max}px range`,
    ]
  }
  return []
}

